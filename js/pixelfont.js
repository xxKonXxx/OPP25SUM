const CHAR_W = 5, CHAR_H = 7, GAP = 1;

export function textWidth(text, scale = 1) {
  return Math.max(0, String(text).length * (CHAR_W + GAP) * scale - GAP * scale);
}

export function drawText(ctx, text, x, y, opts = {}) {
  const scale = opts.scale || 1;
  const color = opts.color || '#ffffff';
  const shadow = opts.shadow;
  const align = opts.align || 'left';
  const str = String(text).toUpperCase();
  const w = textWidth(str, scale);
  let sx = x;
  if (align === 'center') sx = Math.round(x - w / 2);
  else if (align === 'right') sx = Math.round(x - w);
  sx = Math.round(sx);
  y = Math.round(y);

  const drawPass = (ox, oy, col) => {
    ctx.fillStyle = col;
    let cx = sx + ox;
    for (const ch of str) {
      const glyph = G[ch] || G['?'];
      for (let row = 0; row < CHAR_H; row++) {
        const line = glyph[row];
        for (let col2 = 0; col2 < CHAR_W; col2++) {
          if (line[col2] === '1') {
            ctx.fillRect(cx + col2 * scale, y + oy + row * scale, scale, scale);
          }
        }
      }
      cx += (CHAR_W + GAP) * scale;
    }
  };

  if (shadow) drawPass(scale, scale, shadow);
  drawPass(0, 0, color);
  if (opts.outline) {
    // cheap 4-way outline
    drawPass(-scale, 0, opts.outline);
    drawPass(scale, 0, opts.outline);
    drawPass(0, -scale, opts.outline);
    drawPass(0, scale, opts.outline);
    drawPass(0, 0, color);
  }
  return w;
}
